namespace Xoard.App.Theme;

/// <summary>
/// Шутливые подписи под заголовком. Выбираются по дню (а не случайно при каждой отрисовке),
/// чтобы строка не мигала. Когда юмор выключен — спокойная подпись.
/// </summary>
public static class HumorLines
{
    private static readonly string[] Lines =
    [
        "Звуки заряжены. Друзья пока ни о чём не догадываются.",
        "Пульт готов. Осталось дождаться идеального момента.",
        "Микрофон тёплый, звуки свежие.",
        "Тишина в эфире — это просто пауза перед «Ба-дум-тсс».",
        "Лучшая реакция — заранее записанная.",
        "Кнопка «Стоп всё» тоже часть шоу.",
        "Повтор всё слышит. Буквально последние полминуты.",
        "Сегодня отличный день для аплодисментов самому себе.",
    ];

    public const string Plain = "Звуки для Discord и игр — через VB-CABLE.";

    public static string ForToday(bool humor) =>
        humor ? Lines[DateTime.Today.DayOfYear % Lines.Length] : Plain;
}
